# Iter114 UI: kiosk -> + -> Kasgeld -> new mutation -> receipt screen. Paste into browser_automation (TAG/DESC placeholders)
await page.set_viewport_size({"width": 390, "height": 844})
B = "https://vastgoed-app.preview.emergentagent.com"
DESC = "TEST_iter114 UI __TAG__"
try:
    await page.goto(B + "/my-awesome-rentals-bv/kiosk", wait_until="commit")
    await page.wait_for_timeout(4000)
    if await page.locator('[data-testid="keypad-4"]').count():
        for k in "4321":
            await page.click(f'[data-testid="keypad-{k}"]')
            await page.wait_for_timeout(150)
        await page.wait_for_timeout(3000)
    await page.click('[data-testid="kiosk-mobile-fab"]', force=True)
    await page.wait_for_timeout(800)
    await page.click('[data-testid="kiosk-tile-kasgeld"]', force=True)
    await page.wait_for_selector('[data-testid="kasgeld-new-btn"]', timeout=15000)
    await page.wait_for_timeout(1500)
    await page.click('[data-testid="kasgeld-new-btn"]', force=True)
    await page.wait_for_selector('[data-testid="kasgeld-form"]', timeout=5000)
    await page.click('[data-testid="kasgeld-type-out"]', force=True)
    for k in "37":
        await page.click(f'[data-testid="kasgeld-npad-key-{k}"]', force=True)
        await page.wait_for_timeout(100)
    print("amount display", await page.text_content('[data-testid="kasgeld-amount-display"]'))
    await page.click('[data-testid="kasgeld-next-btn"]', force=True)
    await page.wait_for_selector('[data-testid="kasgeld-input-desc"]', timeout=5000)
    await page.fill('[data-testid="kasgeld-input-desc"]', DESC)
    await page.click('[data-testid="kasgeld-save"]', force=True)
    await page.wait_for_selector('[data-testid="kasgeld-receipt-screen"]', timeout=15000)
    print("PASS receipt screen")
    print("amount:", await page.text_content('[data-testid="kasgeld-receipt-amount"]'))
    await page.wait_for_selector('[data-testid="kasgeld-receipt-preview"] img', timeout=10000)
    nw = await page.evaluate("() => document.querySelector('[data-testid=\"kasgeld-receipt-preview\"] img').naturalWidth")
    print("preview img naturalWidth", nw)
    print("title present:", await page.get_by_text("Kasgeld bon", exact=True).count())
    await page.wait_for_timeout(__WAIT__)
    nl = page.locator('[data-testid="kasgeld-print-none"]')
    print("none:", await nl.count(), (await nl.text_content()) if await nl.count() else "")
    print("buttons builtin/ktp/bt:", [await page.locator(f'[data-testid="{t}"]').count() for t in ["kasgeld-print-builtin", "kasgeld-print-ktp", "kasgeld-print-bt"]])
    print("toast ok:", await page.locator('[data-testid="ktp-print-toast-ok"]').count(), "toasts:", await page.evaluate("() => Array.from(document.querySelectorAll('[data-testid^=\"ktp-print-toast\"]')).map(e=>e.dataset.testid+':'+e.textContent)"))
    await page.screenshot(path=".screenshots/i114___TAG__.jpg", quality=40, full_page=False)
    __EXTRA__
    await page.click('[data-testid="kasgeld-receipt-done"]', force=True)
    await page.wait_for_timeout(2500)
    print("form closed:", await page.locator('[data-testid="kasgeld-form"]').count() == 0)
    print("new entry visible:", await page.get_by_text(DESC).count())
except Exception as e:
    print("ERR", e)
    await page.screenshot(path=".screenshots/i114_err.jpg", quality=40, full_page=False)
